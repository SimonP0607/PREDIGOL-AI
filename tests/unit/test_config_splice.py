"""Writing the selection into config/migration.yaml must not cost the file its comments.

The first version of --write-config did `yaml.safe_load` / `yaml.safe_dump`, which kept
every value and dropped every comment - and the comments in that file are where the
measured reasons live: why the injuries cut-off is a partial season, what each endpoint
costs per fixture, which classifications mean "exists, deliberately not fetched". A
config that still parses but no longer says why is a worse config.
"""

from __future__ import annotations

import pytest
import yaml
from scripts.select_competitions import splice_tiers

BEFORE = """\
# Historical migration: what to backfill, in what order, and what it costs.
version: 1

seasons:
  current: 2026          # the season key API-Football calls current
  target_depth: 8        # completed seasons to backfill when the provider has them

endpoints:
  injuries:
    # MEASURED, not assumed: season 2020 runs to May 2021, so the provider's
    # April-2021 cut-off falls INSIDE it.
    since_season_is_partial: true

# Tiers. `fixtures` is the planning estimate per season.
tiers:
  1:
    name: Old tier one
    competitions:
      - league_id: 39
        fixtures: 380

# Live operation reserves its own quota before any backfill runs.
live:
  reserve: 0.10
"""

BLOCK = """\
tiers:
  # Generated by scripts.select_competitions --write-config.
  2:
    name: New tier two
    competitions:
      - league_id: 140
        fixtures: 380
"""


def test_the_tiers_block_is_replaced() -> None:
    after = splice_tiers(BEFORE, BLOCK)
    parsed = yaml.safe_load(after)
    assert list(parsed["tiers"]) == [2]
    assert parsed["tiers"][2]["competitions"][0]["league_id"] == 140
    assert "Old tier one" not in after


def test_every_comment_outside_the_block_survives() -> None:
    after = splice_tiers(BEFORE, BLOCK)
    for comment in (
        "# Historical migration: what to backfill",
        "# the season key API-Football calls current",
        "# MEASURED, not assumed",
        "# April-2021 cut-off falls INSIDE it.",
        "# Tiers. `fixtures` is the planning estimate per season.",
    ):
        assert comment in after, comment


def test_the_comment_above_the_following_key_belongs_to_that_key() -> None:
    """It documents `live:`, not the tiers, so it must end up after the new block."""
    after = splice_tiers(BEFORE, BLOCK)
    note = "# Live operation reserves its own quota"
    assert note in after
    assert after.index(note) < after.index("live:")
    assert after.index("New tier two") < after.index(note)


def test_no_other_value_changes() -> None:
    before, after = yaml.safe_load(BEFORE), yaml.safe_load(splice_tiers(BEFORE, BLOCK))
    assert {k: v for k, v in before.items() if k != "tiers"} \
        == {k: v for k, v in after.items() if k != "tiers"}


def test_a_config_without_a_tiers_key_is_refused_rather_than_guessed_at() -> None:
    with pytest.raises(ValueError, match="no top-level 'tiers:' key"):
        splice_tiers("version: 1\nlive:\n  reserve: 0.10\n", BLOCK)


def test_splicing_twice_is_idempotent() -> None:
    once = splice_tiers(BEFORE, BLOCK)
    assert splice_tiers(once, BLOCK) == once


def test_a_trailing_tiers_block_needs_no_following_key() -> None:
    text = "version: 1\n\n# Tiers.\ntiers:\n  1:\n    name: Old\n"
    after = splice_tiers(text, BLOCK)
    assert "# Tiers." in after and yaml.safe_load(after)["tiers"][2]["name"] == "New tier two"
    assert yaml.safe_load(after)["version"] == 1

"""Domain error hierarchy. Never a bare ``Exception``."""

from __future__ import annotations


class FbiError(Exception):
    """Base for every error raised by this system."""


class ConfigError(FbiError): ...
class ProviderError(FbiError): ...
class RateLimitError(ProviderError): ...
class QuotaExhaustedError(ProviderError): ...
class CircuitOpenError(ProviderError): ...
class ProviderPayloadError(ProviderError): ...
class DataQualityError(FbiError): ...
class TemporalIntegrityError(FbiError):
    """Raised when something would read data that was not knowable at the cutoff."""

"""(the provider's name, the provider's country) of a competition -> (Spanish names, English names). Only competitions whose
usual name in a language is not already the provider's; the rest are found by their own name."""

_TEAM = re.compile(r"^(?P<base>.+?)(?P<women> W)?(?: U(?P<age>\d{2}))?$")
"""A provider name of a national team: the country, then « W» for women's teams, then « U17» … « U23» for an age group."""


@dataclass(frozen=True, slots=True)
class LocalizedName:
    text: str
    language: str  # 'es' or 'en'


def team_names(provider_name: str) -> Iterator[LocalizedName]:
    """The Spanish and English names of a national team, from its provider name: «Spain» → «España»; «Germany U21» →
    «Alemania Sub-21», and «Mexico W U17» → «México Femenina Sub-17» / «Mexico Women U17». Nothing for a name it does not
    know. The provider's own name is not repeated."""
    m = _TEAM.match(provider_name.strip())
    if m is None:
        return
    code = PROVIDER_COUNTRY.get(m["base"])
    if code is None:
        return
    es_names, en_names = COUNTRY_NAMES[code]
    women, age = m["women"] is not None, m["age"]
    for base in es_names:
        yield LocalizedName(base + (" Femenina" if women else "") + (f" Sub-{age}" if age else ""), "es")
    for base in en_names:
        yield LocalizedName(base + (" Women" if women else "") + (f" U{age}" if age else ""), "en")


def competition_names(provider_name: str, country: str) -> Iterator[LocalizedName]:
    """The Spanish and English names of a competition, by its provider name and country; nothing when it is not listed."""
    names = COMPETITION_NAMES.get((provider_name.strip(), (country or "").strip()))
    if names is None:
        return
    es_names, en_names = names
    for text in es_names:
        yield LocalizedName(text, "es")
    for text in en_names:
        yield LocalizedName(text, "en")
